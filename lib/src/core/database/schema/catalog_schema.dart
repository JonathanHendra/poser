import 'schema_helpers.dart';

final catalogSchema = <String>[
  scopedTable('stores', [
    'name TEXT NOT NULL',
    'address TEXT NOT NULL DEFAULT \'\'',
    'active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))',
  ]),
  'CREATE TABLE users (owner_id TEXT NOT NULL REFERENCES businesses(owner_id), id TEXT NOT NULL, google_id TEXT NOT NULL, display_name TEXT NOT NULL, email TEXT, active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)), PRIMARY KEY(owner_id,id), UNIQUE(owner_id,google_id))',
  scopedTable('categories', [
    'name TEXT NOT NULL COLLATE NOCASE',
    'UNIQUE(owner_id,name)',
  ]),
  scopedTable('brands', [
    'name TEXT NOT NULL COLLATE NOCASE',
    'UNIQUE(owner_id,name)',
  ]),
  scopedTable('units', [
    'name TEXT NOT NULL COLLATE NOCASE',
    'symbol TEXT',
    'precision_digits INTEGER NOT NULL DEFAULT 0 CHECK(precision_digits BETWEEN 0 AND 9)',
    'UNIQUE(owner_id,name)',
  ]),
  scopedTable('products', [
    'name TEXT NOT NULL',
    'sku TEXT',
    'barcode TEXT',
    'category_id INTEGER',
    'brand_id INTEGER',
    'base_unit_id INTEGER NOT NULL',
    "product_type TEXT NOT NULL DEFAULT 'goods' CHECK(product_type IN ('goods','service'))",
    'allow_negative_stock INTEGER NOT NULL DEFAULT 0 CHECK(allow_negative_stock IN (0,1))',
    'active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))',
    ...fraction('minimum_stock'),
    'UNIQUE(owner_id,sku)',
    'UNIQUE(owner_id,barcode)',
    'UNIQUE(owner_id,id,base_unit_id)',
    reference('category_id', 'categories'),
    reference('brand_id', 'brands'),
    reference('base_unit_id', 'units'),
  ]),
  scopedTable('product_variants', [
    'product_id INTEGER NOT NULL',
    'name TEXT NOT NULL',
    'sku TEXT',
    'barcode TEXT',
    'active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))',
    reference('product_id', 'products'),
    'UNIQUE(owner_id,product_id,id)',
    'UNIQUE(owner_id,product_id,name)',
    'UNIQUE(owner_id,sku)',
    'UNIQUE(owner_id,barcode)',
  ]),
  scopedTable('product_attributes', [
    'product_id INTEGER NOT NULL',
    'variant_id INTEGER',
    'name TEXT NOT NULL',
    'value TEXT NOT NULL',
    reference('product_id', 'products'),
    'FOREIGN KEY(owner_id,product_id,variant_id) REFERENCES product_variants(owner_id,product_id,id)',
  ]),
  'CREATE UNIQUE INDEX product_attribute_unique ON product_attributes(owner_id,product_id,IFNULL(variant_id,0),name)',
  scopedTable('unit_conversions', [
    'product_id INTEGER NOT NULL',
    'from_unit_id INTEGER NOT NULL',
    'to_unit_id INTEGER NOT NULL',
    ...fraction('ratio', positive: true),
    'CHECK(from_unit_id != to_unit_id)',
    'UNIQUE(owner_id,product_id,from_unit_id,to_unit_id)',
    reference('product_id', 'products'),
    reference('from_unit_id', 'units'),
    reference('to_unit_id', 'units'),
  ]),
  scopedTable('price_lists', [
    'name TEXT NOT NULL',
    "kind TEXT NOT NULL CHECK(kind IN ('retail','packaging','wholesale','member','reseller','promo','customer'))",
    'is_default INTEGER NOT NULL DEFAULT 0 CHECK(is_default IN (0,1))',
    'starts_at INTEGER',
    'ends_at INTEGER',
    'CHECK(ends_at IS NULL OR starts_at IS NULL OR ends_at > starts_at)',
    'UNIQUE(owner_id,name)',
  ]),
  'CREATE UNIQUE INDEX price_list_one_default ON price_lists(owner_id) WHERE is_default = 1',
  scopedTable('product_prices', [
    'product_id INTEGER NOT NULL',
    'variant_id INTEGER',
    'unit_id INTEGER NOT NULL',
    'price_list_id INTEGER NOT NULL',
    'customer_id INTEGER',
    ...fraction('minimum_quantity'),
    amount('price'),
    reference('product_id', 'products'),
    reference('unit_id', 'units'),
    reference('price_list_id', 'price_lists'),
    reference('customer_id', 'customers'),
    'FOREIGN KEY(owner_id,product_id,variant_id) REFERENCES product_variants(owner_id,product_id,id)',
  ]),
  'CREATE UNIQUE INDEX product_price_tier ON product_prices(owner_id,product_id,IFNULL(variant_id,0),unit_id,price_list_id,IFNULL(customer_id,0),minimum_quantity_num,minimum_quantity_den)',
  scopedTable('packages', [
    'name TEXT NOT NULL',
    amount('price'),
    'active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))',
  ]),
  scopedTable('package_items', [
    'package_id INTEGER NOT NULL',
    'product_id INTEGER NOT NULL',
    'variant_id INTEGER',
    'unit_id INTEGER NOT NULL',
    ...fraction('quantity', positive: true),
    reference('package_id', 'packages'),
    reference('product_id', 'products'),
    reference('unit_id', 'units'),
    'FOREIGN KEY(owner_id,product_id,variant_id) REFERENCES product_variants(owner_id,product_id,id)',
  ]),
  'CREATE INDEX idx_products_owner_v2 ON products(owner_id,name)',
  'CREATE INDEX idx_product_prices_lookup ON product_prices(owner_id,product_id,unit_id,price_list_id)',
  'CREATE INDEX idx_conversions_product ON unit_conversions(owner_id,product_id)',
];
