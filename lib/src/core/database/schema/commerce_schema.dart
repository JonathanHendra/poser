import 'schema_helpers.dart';

final commerceSchema = <String>[
  scopedTable('suppliers', [
    'name TEXT NOT NULL',
    'phone TEXT',
    'address TEXT',
    'email TEXT',
  ]),
  scopedTable('customers', [
    'name TEXT NOT NULL',
    'phone TEXT',
    'address TEXT',
    'email TEXT',
    'price_list_id INTEGER',
    reference('price_list_id', 'price_lists'),
  ]),
  scopedTable('purchases', [
    'store_id INTEGER NOT NULL',
    'supplier_id INTEGER',
    'reference TEXT NOT NULL',
    "status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','ordered','partially_received','received','completed','cancelled'))",
    amount('subtotal'),
    amount('discount'),
    amount('tax'),
    amount('total'),
    'created_at INTEGER NOT NULL',
    'created_by TEXT',
    reference('store_id', 'stores'),
    reference('supplier_id', 'suppliers'),
    'FOREIGN KEY(owner_id,created_by) REFERENCES users(owner_id,id)',
    'UNIQUE(owner_id,reference)',
  ]),
  scopedTable('purchase_items', [
    'purchase_id INTEGER NOT NULL',
    'product_id INTEGER NOT NULL',
    'variant_id INTEGER',
    'unit_id INTEGER NOT NULL',
    'product_name TEXT NOT NULL',
    'unit_name TEXT NOT NULL',
    ...fraction('quantity', positive: true),
    ...fraction('received_quantity'),
    ...fraction('conversion', positive: true),
    amount('unit_cost'),
    amount('total'),
    reference('purchase_id', 'purchases'),
    reference('product_id', 'products'),
    reference('unit_id', 'units'),
    'FOREIGN KEY(owner_id,product_id,variant_id) REFERENCES product_variants(owner_id,product_id,id)',
  ]),
  scopedTable('cash_shifts', [
    'store_id INTEGER NOT NULL',
    'user_id TEXT NOT NULL',
    'opened_at INTEGER NOT NULL',
    'closed_at INTEGER',
    amount('opening_cash'),
    amount('closing_cash'),
    amount('expected_cash'),
    amount('difference', signed: true),
    reference('store_id', 'stores'),
    'FOREIGN KEY(owner_id,user_id) REFERENCES users(owner_id,id)',
    'CHECK(closed_at IS NULL OR closed_at >= opened_at)',
  ]),
  scopedTable('sales', [
    'store_id INTEGER NOT NULL',
    'customer_id INTEGER',
    'cash_shift_id INTEGER',
    'request_key TEXT NOT NULL',
    "status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','completed','void'))",
    amount('subtotal'),
    amount('discount'),
    amount('tax'),
    amount('total'),
    amount('cost'),
    amount('gross_profit', signed: true),
    'created_at INTEGER NOT NULL',
    'created_by TEXT NOT NULL',
    reference('store_id', 'stores'),
    reference('customer_id', 'customers'),
    reference('cash_shift_id', 'cash_shifts'),
    'FOREIGN KEY(owner_id,created_by) REFERENCES users(owner_id,id)',
    'UNIQUE(owner_id,request_key)',
  ]),
  scopedTable('sale_items', [
    'sale_id INTEGER NOT NULL',
    'product_id INTEGER NOT NULL',
    'variant_id INTEGER',
    'unit_id INTEGER NOT NULL',
    'price_list_id INTEGER NOT NULL',
    'product_name TEXT NOT NULL',
    'unit_name TEXT NOT NULL',
    ...fraction('quantity', positive: true),
    ...fraction('conversion', positive: true),
    ...fraction('base_quantity', positive: true),
    amount('unit_price'),
    amount('subtotal'),
    amount('discount'),
    amount('tax'),
    amount('total'),
    amount('cost'),
    reference('sale_id', 'sales'),
    reference('product_id', 'products'),
    reference('unit_id', 'units'),
    reference('price_list_id', 'price_lists'),
    'FOREIGN KEY(owner_id,product_id,variant_id) REFERENCES product_variants(owner_id,product_id,id)',
  ]),
  scopedTable('sale_payments', [
    'sale_id INTEGER NOT NULL',
    "method TEXT NOT NULL CHECK(method IN ('cash','qris','transfer','debit','credit','ewallet','other'))",
    amount('amount'),
    'reference TEXT',
    "verification_status TEXT NOT NULL DEFAULT 'recorded' CHECK(verification_status IN ('recorded','verified','failed'))",
    'created_at INTEGER NOT NULL',
    reference('sale_id', 'sales'),
  ]),
  scopedTable('sales_returns', [
    'store_id INTEGER NOT NULL',
    'sale_id INTEGER',
    'purchase_id INTEGER',
    "return_type TEXT NOT NULL CHECK(return_type IN ('sale','purchase'))",
    'request_key TEXT NOT NULL',
    'reason TEXT NOT NULL',
    amount('refund_amount'),
    'created_at INTEGER NOT NULL',
    'created_by TEXT NOT NULL',
    reference('store_id', 'stores'),
    reference('sale_id', 'sales'),
    reference('purchase_id', 'purchases'),
    'FOREIGN KEY(owner_id,created_by) REFERENCES users(owner_id,id)',
    "CHECK((return_type = 'sale' AND sale_id IS NOT NULL AND purchase_id IS NULL) OR (return_type = 'purchase' AND purchase_id IS NOT NULL AND sale_id IS NULL))",
    'UNIQUE(owner_id,request_key)',
  ]),
  'ALTER TABLE sales ADD COLUMN request_payload TEXT NOT NULL DEFAULT \'{}\'',
  'ALTER TABLE sales ADD COLUMN cost_known INTEGER NOT NULL DEFAULT 0 CHECK(cost_known IN (0,1))',
  'ALTER TABLE sale_items ADD COLUMN cost_known INTEGER NOT NULL DEFAULT 0 CHECK(cost_known IN (0,1))',
  'ALTER TABLE sale_payments ADD COLUMN tendered INTEGER NOT NULL DEFAULT 0 CHECK(typeof(tendered) = \'integer\' AND tendered BETWEEN 0 AND 9007199254740991)',
  'CREATE INDEX idx_sales_date ON sales(owner_id,store_id,created_at)',
  'CREATE INDEX idx_purchases_date ON purchases(owner_id,store_id,created_at)',
  'CREATE INDEX idx_sale_items_sale ON sale_items(owner_id,sale_id)',
  'CREATE INDEX idx_purchase_items_purchase ON purchase_items(owner_id,purchase_id)',
  'CREATE INDEX idx_payments_sale ON sale_payments(owner_id,sale_id)',
];
